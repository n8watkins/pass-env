// Writes the Homebrew formula for one release from its SHA256SUMS:
//   node packaging/homebrew.mjs <version> <SHA256SUMS> > Formula/pass-env.rb
// The formula installs the release's standalone binary for the Mac or Linux
// machine it runs on, and depends on pass (which brings gnupg).
import { readFileSync } from "node:fs";

const [version, sumsFile] = process.argv.slice(2);
if (!/^\d+\.\d+\.\d+$/.test(version ?? "") || !sumsFile) {
	console.error("usage: node packaging/homebrew.mjs <version, e.g. 1.2.0> <SHA256SUMS>");
	process.exit(2);
}
const sums = new Map(readFileSync(sumsFile, "utf8").trim().split("\n").map((line) => {
	const [hash, file] = line.split(/\s+/);
	return [file, hash];
}));
const asset = (name) => {
	const hash = sums.get(name);
	if (!/^[0-9a-f]{64}$/.test(hash ?? "")) throw new Error(`SHA256SUMS has no hash for ${name}`);
	const url = `https://github.com/n8watkins/pass-env/releases/download/v${version}/${name}`;
	return `      url "${url}"\n      sha256 "${hash}"`;
};

process.stdout.write(`# Generated by packaging/homebrew.mjs in n8watkins/pass-env for v${version}; do not edit.
class PassEnv < Formula
  desc "Use secrets from pass without them landing in files or agent transcripts"
  homepage "https://github.com/n8watkins/pass-env"
  license "MIT"

  depends_on "pass"

  on_macos do
    on_arm do
${asset("pass-env-darwin-arm64")}
    end
    on_intel do
${asset("pass-env-darwin-x64")}
    end
  end

  on_linux do
    on_arm do
${asset("pass-env-linux-arm64")}
    end
    on_intel do
${asset("pass-env-linux-x64")}
    end
  end

  def install
    bin.install Dir["pass-env-*"].first => "pass-env"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/pass-env version")
  end
end
`);
